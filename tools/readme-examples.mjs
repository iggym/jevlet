// Prints the README "Worked examples" block from web/assets/examples.js.
// Usage: node tools/readme-examples.mjs > /tmp/block.md   (test/examples.test.mjs checks README matches)
import { EXAMPLES, exampleCurl, exampleFetch, exampleResponse } from "../web/assets/examples.js";

export function readmeExamples(origin = "https://jevlet.iggy-mw.workers.dev") {
  const parts = ["<!-- examples:start (generated by tools/readme-examples.mjs; do not edit by hand) -->"];
  for (const ex of EXAMPLES) {
    parts.push(
      `### ${ex.title}`,
      "",
      `\`${ex.method} ${ex.path}\` → HTTP ${ex.status}`,
      "",
      "```bash",
      exampleCurl(ex, origin),
      "```",
      "",
      "<details><summary>JavaScript fetch</summary>",
      "",
      "```js",
      exampleFetch(ex, origin),
      "```",
      "",
      "</details>",
      "",
      `Response (${ex.trimmed ? `live, ${ex.trimmed}` : "live, unedited"}):`,
      "",
      "```" + (typeof ex.response === "string" ? "csv" : "json"),
      exampleResponse(ex),
      "```",
      "",
      `**How to read it:** ${ex.read}`,
      ""
    );
  }
  parts.push("<!-- examples:end -->");
  return parts.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) console.log(readmeExamples());
